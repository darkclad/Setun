fn rows(r: &[&str; 8]) -> [u8; 8] {
    let mut g = [0u8; 8];
    for (y, row) in r.iter().enumerate() {
        for (x, c) in row.chars().enumerate() {
            if c == '#' {
                g[y] |= 1 << x;
            }
        }
    }
    g
}

fn font8x8(c: char) -> Option<[u8; 8]> {
    use font8x8::UnicodeFonts;
    font8x8::BASIC_FONTS
        .get(c)
        .or_else(|| font8x8::LATIN_FONTS.get(c))
        .or_else(|| font8x8::GREEK_FONTS.get(c))
        .or_else(|| font8x8::BOX_FONTS.get(c))
        .or_else(|| font8x8::BLOCK_FONTS.get(c))
        .or_else(|| font8x8::MISC_FONTS.get(c))
}

/// An overlined character, which the machine's character set writes as the
/// negated code point (a negative digit `1̅` is −'1'): the glyph moved down
/// one row, with a bar across columns 0–6 on the freed top row. Digits and
/// capitals stand on rows 0–6, so their bottom row was empty anyway.
pub fn overlined(g: [u8; 8]) -> [u8; 8] {
    let mut out = [0u8; 8];
    out[0] = 0x7F;
    out[1..].copy_from_slice(&g[..7]);
    out
}

/// The 8×8 glyph of a code point (bit 0 = leftmost pixel), or None when the
/// font has none.
pub fn glyph8x8(cp: u32) -> Option<[u8; 8]> {
    static CYR: OnceLock<Vec<[u8; 8]>> = OnceLock::new();
    if (CYRILLIC_FIRST..=CYRILLIC_LAST).contains(&cp) {
        let table = CYR.get_or_init(|| {
            CYRILLIC
                .iter()
                .map(|s| match s {
                    Same(c) => font8x8(*c).expect("a font8x8 character"),
                    Rows(r) => rows(r),
                })
                .collect()
        });
        return Some(table[(cp - CYRILLIC_FIRST) as usize]);
    }
    if cp == NUMERO {
        return Some(rows(&["#...#...", "##..#.#.", "#.#.##.#", "#..##.#.", "#...#...", "#...####", "#...#...", B]));
    }
    font8x8(char::from_u32(cp)?)
}
