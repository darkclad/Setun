"""AES-GCM, ECDH and ECDSA signing test vectors for user/bin/pktest.tri, from Python's cryptography
(an implementation independent of user/lib/aes.tri).
Usage: python tools/aesvectors.py > user/bin/aesvectors.inc.tri"""
import sys
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

def h(b):
    return b.hex()

out = ["// generated by tools/aesvectors.py (Python cryptography)"]
# key, nonce, aad and message lengths that cross the block edges
cases = [(16, 0, 0), (16, 13, 16), (16, 20, 60), (32, 0, 17), (32, 12, 64), (16, 0, 300)]
for i, (klen, alen, mlen) in enumerate(cases):
    key = bytes((7 * j + 3 * i + 1) % 256 for j in range(klen))
    nonce = bytes((11 * j + i) % 256 for j in range(12))
    aad = bytes((5 * j + 2) % 256 for j in range(alen))
    msg = bytes((13 * j + i * 17) % 256 for j in range(mlen))
    ct = AESGCM(key).encrypt(nonce, msg, aad)
    for name, val in [("KEY", key), ("NONCE", nonce), ("AAD", aad), ("MSG", msg), ("CT", ct)]:
        out.append(f'const G{i}_{name}: *char = "{h(val)}";')
# ECDH on P-256 and P-384: two fixed keys and their shared secret
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives import serialization

def pub(k):
    return k.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)

for tag, curve, nb in [("P256", ec.SECP256R1(), 32), ("P384", ec.SECP384R1(), 48)]:
    ka = ec.derive_private_key(int.from_bytes(bytes(range(3, 3 + nb)), "big"), curve)
    kb = ec.derive_private_key(int.from_bytes(bytes(range(200, 200 - nb, -1)), "big"), curve)
    out.append(f'const X{tag}_A: *char = "{ka.private_numbers().private_value.to_bytes(nb, "big").hex()}";')
    out.append(f'const X{tag}_B: *char = "{kb.private_numbers().private_value.to_bytes(nb, "big").hex()}";')
    out.append(f'const X{tag}_APUB: *char = "{h(pub(ka))}";')
    out.append(f'const X{tag}_BPUB: *char = "{h(pub(kb))}";')
    out.append(f'const X{tag}_SHARED: *char = "{h(ka.exchange(ec.ECDH(), kb.public_key()))}";')
# deterministic ECDSA (RFC 6979): fixed keys, a few messages
from cryptography.hazmat.primitives.asymmetric import utils
from cryptography.hazmat.primitives import hashes
for tag, curve, nb, hsh in [("P256", ec.SECP256R1(), 32, hashes.SHA256()), ("P384", ec.SECP384R1(), 48, hashes.SHA384())]:
    d = int("C9AFA9D845BA75166B5C215767B1D6934E50C3DB36E89B127B8A622B120F6721", 16) if tag == "P256" else \
        int("6B9D3DAD2E1B8C1C05B19875B6659F4DE23C3B667BF297BA9AA47740787137D896D5724E4C70A825F872C9EA60D2EDF5", 16)
    k = ec.derive_private_key(d, curve)
    out.append(f'const S{tag}_D: *char = "{d.to_bytes(nb, "big").hex()}";')
    out.append(f'const S{tag}_PUB: *char = "{h(pub(k))}";')
    for i, msg in enumerate([b"sample", b"test", b"Setun-11 signs " * 20]):
        r, s = utils.decode_dss_signature(k.sign(msg, ec.ECDSA(hsh, deterministic_signing=True)))
        out.append(f'const S{tag}_M{i}: *char = "{h(msg)}";')
        out.append(f'const S{tag}_R{i}: *char = "{r.to_bytes(nb, "big").hex()}";')
        out.append(f'const S{tag}_S{i}: *char = "{s.to_bytes(nb, "big").hex()}";')
sys.stdout.reconfigure(newline='\n')   # LF, also on Windows
print("\n".join(out))
