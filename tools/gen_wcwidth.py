"""Generate user/lib/wcwidth.tri: which characters take two terminal cells.

Input: Unicode's EastAsianWidth.txt
(https://www.unicode.org/Public/UCD/latest/ucd/EastAsianWidth.txt).
Characters whose East_Asian_Width is W (wide) or F (fullwidth) take two
cells, as wcwidth() has it; everything else takes one.

    python tools/gen_wcwidth.py EastAsianWidth.txt > user/lib/wcwidth.tri
"""

import sys


def ranges(path):
    rs = []
    version = '?'
    for line in open(path, encoding='utf-8'):
        if line.startswith('# EastAsianWidth-'):
            version = line[len('# EastAsianWidth-'):].split('.txt')[0]
        line = line.split('#')[0].strip()
        if not line:
            continue
        r, prop = [x.strip() for x in line.split(';')]
        if prop not in ('W', 'F'):
            continue
        a, _, b = r.partition('..')
        rs.append([int(a, 16), int(b or a, 16)])
    rs.sort()
    merged = []
    for a, b in rs:
        if merged and a <= merged[-1][1] + 1:
            merged[-1][1] = max(merged[-1][1], b)
        else:
            merged.append([a, b])
    return version, merged


def main():
    version, rs = ranges(sys.argv[1])
    out = sys.stdout
    out.write('// Generated by tools/gen_wcwidth.py from EastAsianWidth-%s.txt: do not edit.\n' % version)
    out.write('//\n// tchar_width(cp): the terminal cells character cp takes (an overlined\n')
    out.write('// one, negative, as many as the plain one): 2 for East Asian Wide and\n')
    out.write('// Fullwidth characters, 1 for everything else.\n\n')
    out.write('const WIDE_RANGES: int = %d;\n\n' % len(rs))
    for name, k in (('wide_first', 0), ('wide_last', 1)):
        out.write('var %s: [%d]int = {\n' % (name, len(rs)))
        vals = ['%d' % r[k] for r in rs]
        for i in range(0, len(vals), 9):
            out.write('    ' + ', '.join(vals[i:i + 9]) + (',' if i + 9 < len(vals) else '') + '\n')
        out.write('};\n\n')
    out.write('''fn tchar_width(cp: int) -> int {
    if (cp < 0) { cp = -cp; }
    if (cp < 4352) { return 1; }                   // nothing wide below U+1100
    var lo: int = 0;
    var hi: int = WIDE_RANGES - 1;
    while (lo <= hi) {
        var mid: int = (lo + hi) / 2;
        if (cp < wide_first[mid]) { hi = mid - 1; }
        else if (cp > wide_last[mid]) { lo = mid + 1; }
        else { return 2; }
    }
    return 1;
}

// The cells a string takes (a malformed character counts as one).
fn tstr_width(s: *char) -> int {
    var n: int = 0;
    var cp: int;
    loop {
        var k: int = tstr_next(s, &cp);
        if (k == 0) { return n; }
        if (k < 0) { n += 1; s = s + 1; continue; }
        n += tchar_width(cp);
        s = s + k;
    }
    return n;
}
''')


main()
