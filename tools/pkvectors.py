"""ECDSA, RSA and AEAD test vectors for user/bin/pktest.tri, from Python's
cryptography (an implementation independent of user/lib/). New keys each
run. Usage: python tools/pkvectors.py user/bin/pkvectors.inc.tri"""
import hashlib, hmac, os
from cryptography.hazmat.primitives.asymmetric import ec, rsa, padding, utils
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

out = []
def v(name, data):
    out.append((name, data.hex() if isinstance(data, bytes) else data))

msg = b"Setun-11 says: ternary is the most efficient base"
v("msg", msg)
# ECDSA
for curve, hname, h, tag in [(ec.SECP256R1(), "sha256", hashes.SHA256(), "p256"), (ec.SECP384R1(), "sha384", hashes.SHA384(), "p384")]:
    k = ec.generate_private_key(curve)
    pub = k.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
    sig = k.sign(msg, ec.ECDSA(h))
    r, s = utils.decode_dss_signature(sig)
    nb = 32 if tag == "p256" else 48
    v(tag + "_pub", pub)
    v(tag + "_r", r.to_bytes(nb, "big"))
    v(tag + "_s", s.to_bytes(nb, "big"))
    v(tag + "_h", hashlib.new(hname, msg).digest())
    v(tag + "_der", sig)
# P-256 key signing SHA-384 (hash truncated)
k = ec.generate_private_key(ec.SECP256R1())
sig = k.sign(msg, ec.ECDSA(hashes.SHA384()))
r, s = utils.decode_dss_signature(sig)
v("p256x_pub", k.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint))
v("p256x_r", r.to_bytes(32, "big")); v("p256x_s", s.to_bytes(32, "big")); v("p256x_h", hashlib.sha384(msg).digest())
# RSA
for bits, tag in [(2048, "r2048"), (4096, "r4096")]:
    k = rsa.generate_private_key(public_exponent=65537, key_size=bits)
    n = k.public_key().public_numbers().n
    v(tag + "_n", n.to_bytes(bits // 8, "big"))
    v(tag + "_pkcs1_256", k.sign(msg, padding.PKCS1v15(), hashes.SHA256()))
    v(tag + "_pss_256", k.sign(msg, padding.PSS(mgf=padding.MGF1(hashes.SHA256()), salt_length=32), hashes.SHA256()))
    v(tag + "_pkcs1_384", k.sign(msg, padding.PKCS1v15(), hashes.SHA384()))
    v(tag + "_pss_384", k.sign(msg, padding.PSS(mgf=padding.MGF1(hashes.SHA384()), salt_length=48), hashes.SHA384()))
v("h256", hashlib.sha256(msg).digest())
v("h384", hashlib.sha384(msg).digest())
# AEAD (RFC 8439 2.8.2)
key = bytes(range(0x80, 0xa0))
nonce = bytes.fromhex("070000004041424344454647")
aad = bytes.fromhex("50515253c0c1c2c3c4c5c6c7")
pt = b"Ladies and Gentlemen of the class of '99: If I could offer you only one tip for the future, sunscreen would be it."
v("aead_ct", ChaCha20Poly1305(key).encrypt(nonce, pt, aad))
lines = ["// generated by pkvectors.py (Python cryptography)"]
for name, hx in out:
    lines.append(f'const V_{name.upper()}: *char = "{hx}";')
import sys
open(sys.argv[1], "w").write("\n".join(lines) + "\n")
sys.stdout.reconfigure(newline='\n')   # LF, also on Windows
print(len(out))
